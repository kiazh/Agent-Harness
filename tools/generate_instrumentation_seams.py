#!/usr/bin/env python3
"""Generate ``machina/observability/instrumentation_seams.py``.

The catalog is derived, never hand-maintained: every ``instrument(...)`` /
``instrumented(...)`` call site in the product package is scanned with the
AST, and the enclosing module/qualname is recorded with the literal
component and operation. Output is sorted and stable, so the committed file
can be verified by regenerating it (``--check`` or a test that diffs a
temporary output).

Usage:
    python tools/generate_instrumentation_seams.py
    python tools/generate_instrumentation_seams.py --output /tmp/seams.py
    python tools/generate_instrumentation_seams.py --check
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

HEADER = "# GENERATED by tools/generate_instrumentation_seams.py — do not edit"
PACKAGE = "machina"
OUTPUT_RELATIVE = Path("machina") / "observability" / "instrumentation_seams.py"
TARGET_NAMES = frozenset({"instrument", "instrumented", "instrumented_provider"})
#: Scanner name → catalog ``kind`` value.
KINDS = {
    "instrument": "instrument",
    "instrumented": "instrumented",
    "instrumented_provider": "instrumented",
}


class _SeamScanner(ast.NodeVisitor):
    """Collect literal ``instrument``/``instrumented`` call sites."""

    def __init__(self, module: str, source: str) -> None:
        self.module = module
        self.source = source
        self.scope: list[str] = []
        self.seams: set[tuple[str, str, str, str, str]] = set()

    def _qualname(self) -> str:
        return ".".join(self.scope)

    def _record(self, node: ast.Call, kind: str) -> None:
        component: str | None = None
        operation: str | None = None
        if (
            getattr(node.func, "id", None) == "instrumented_provider"
            or getattr(node.func, "attr", None) == "instrumented_provider"
        ) and node.args:
            component = "provider"
            if isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                operation = node.args[0].value
        elif len(node.args) >= 2 and all(
            isinstance(arg, ast.Constant) and isinstance(arg.value, str) for arg in node.args[:2]
        ):
            component = node.args[0].value
            operation = node.args[1].value
        for keyword in node.keywords:
            if keyword.arg == "component" and isinstance(keyword.value, ast.Constant):
                component = keyword.value.value
            elif keyword.arg == "operation" and isinstance(keyword.value, ast.Constant):
                operation = keyword.value.value
        if not isinstance(component, str) or not isinstance(operation, str):
            line = getattr(node, "lineno", 0)
            print(
                f"warning: non-literal {kind}() at {self.module}:{line}; skipped",
                file=sys.stderr,
            )
            return
        self.seams.add((component, operation, self.module, self._qualname(), kind))

    def _visit_scoped(self, node: ast.AST, name: str) -> None:
        # Decorators are evaluated in the ENCLOSING scope, so visit them
        # before entering the function/class body.
        for decorator in getattr(node, "decorator_list", []):
            self.visit(decorator)
        self.scope.append(name)
        try:
            for child in ast.iter_child_nodes(node):
                if child in getattr(node, "decorator_list", []):
                    continue
                self.visit(child)
        finally:
            self.scope.pop()

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
        self._visit_scoped(node, node.name)

    def visit_AsyncFunctionDef(self, node: ast.AsyncFunctionDef) -> None:
        self._visit_scoped(node, node.name)

    def visit_ClassDef(self, node: ast.ClassDef) -> None:
        self._visit_scoped(node, node.name)

    def visit_Call(self, node: ast.Call) -> None:
        func = node.func
        name = func.id if isinstance(func, ast.Name) else getattr(func, "attr", "")
        if name in TARGET_NAMES:
            self._record(node, KINDS[name])
        self.generic_visit(node)


def _module_name(path: Path, root: Path) -> str:
    relative = path.relative_to(root).with_suffix("")
    parts = list(relative.parts)
    if parts and parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def collect(root: Path) -> list[tuple[str, str, str, str, str]]:
    package = root / PACKAGE
    seams: set[tuple[str, str, str, str, str]] = set()
    ignored = {
        package / "observability" / "instrumentation.py",
        package / "observability" / "instrumentation_seams.py",
    }
    for path in sorted(package.rglob("*.py")):
        if "__pycache__" in path.parts or path in ignored:
            continue
        try:
            source = path.read_text(encoding="utf-8")
            tree = ast.parse(source, filename=str(path))
        except (OSError, SyntaxError) as error:
            print(f"warning: cannot scan {path}: {error}", file=sys.stderr)
            continue
        scanner = _SeamScanner(_module_name(path, root), source)
        scanner.visit(tree)
        seams.update(scanner.seams)
    return sorted(seams)


def render(seams: list[tuple[str, str, str, str, str]]) -> str:
    lines = [
        HEADER,
        "",
        '"""Catalog of instrumented seams (generated; do not edit by hand).',
        "",
        "Each entry is ``(component, operation, module, qualname, kind)`` where",
        "``kind`` is ``instrument`` for a context manager or ``instrumented``",
        "for the decorator form. Regenerate with",
        "``python tools/generate_instrumentation_seams.py``.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "SEAMS: tuple[tuple[str, str, str, str, str], ...] = (",
    ]
    if not seams:
        lines.append("    # No instrumented seams found.")
    for seam in seams:
        lines.append("    (")
        # Emit double-quoted literals so regeneration matches Ruff's formatting.
        lines.extend(f"        {json.dumps(value, ensure_ascii=False)}," for value in seam)
        lines.append("    ),")
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="repository root containing the machina package",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="output path (defaults to the committed generated module)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when the committed catalog is stale",
    )
    args = parser.parse_args(argv)

    root = args.root.resolve()
    output = (args.output or (root / OUTPUT_RELATIVE)).resolve()
    seams = collect(root)
    rendered = render(seams)
    if args.check:
        try:
            current = output.read_text(encoding="utf-8")
        except OSError as error:
            print(f"cannot read {output}: {error}", file=sys.stderr)
            return 2
        if current != rendered:
            print(f"instrumentation catalog is stale: {output}", file=sys.stderr)
            return 1
        print(f"instrumentation catalog is current: {output}")
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered, encoding="utf-8")
    print(f"wrote {len(seams)} seams to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
